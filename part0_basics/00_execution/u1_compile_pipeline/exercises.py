# ═══════════════════════════════════════════════════
# 유제 2. constant folding 확인
# ═══════════════════════════════════════════════════
def a():
    return 2 ** 10

def b(n):
    return 2 ** n

print("=== a의 바이트코드 ===")
dis.dis(a)
print("\n=== b의 바이트코드 ===")
dis.dis(b)

# 관찰: a와 b의 바이트코드에서 달라지는 줄은?
#   → a는 계산 결과가 바이트 코드에 보인다. (1024) 그러나 b는 보이지 않는다. 
"""
=== a의 바이트코드 ===
 35           0 RESUME                   0

 36           2 RETURN_CONST             1 (1024)

=== b의 바이트코드 ===
 38           0 RESUME                   0

 39           2 LOAD_CONST               1 (2)
              4 LOAD_FAST                0 (n)
              6 BINARY_OP                8 (**)
             10 RETURN_VALUE
"""
#
# 이유: 왜 a는 되고 b는 안 되는가?
#   → 매개변수로 값을 받기때문에 런타임에야 계산결과가 정해지므로 컴파일 단계에서 값이 고정되지 않는다.


