#   c = Circular([1,2,3])
#   c[0] → 1,  c[3] → 1,  c[4] → 2,  c[-1] → 3

class Circular:
    def __init__(self, data):
        self.data = data
    # TODO: __getitem__ 구현 (정수 인덱스만 지원하면 됨)
    def __getitem__(self, key):
        size = len(self.data)
        if size < 0 :
            key = -1 * key
        return self.data[key % size]

