a = [1, 2, 3]; b = a
a = a[:]
a.append(4)
print("  B) b =", b, "  예측:__[1,2,3]")

# (C)
a = [[1], [2]]; b = a[:]
b[0].append(99)
print("  C) a =", a, "  예측:__[[1,99], [2]]")

# (D)
a = [[1], [2]]; b = a[:]
b[0] = [99]
print("  D) a =", a, "  예측:__[[1],[2]]")

