# 유제 2. 버그 찾기 — 두 번 순회하는 함수
# ═══════════════════════════════════════════════════
# 아래 함수는 평균을 구한다. 리스트를 넘기면 잘 되는데,
# 제너레이터를 넘기면 ZeroDivisionError가 난다.

def average(numbers):
    total = sum(numbers)
    count = len(list(numbers))      # 두 번째 순회
    return total / count

print("\n=== 유제2 ===")
print("  리스트   :", average([1, 2, 3]))
try:
    print("  제너레이터:", average(x for x in [1, 2, 3]))
except ZeroDivisionError:
    print("  제너레이터: ZeroDivisionError!")

