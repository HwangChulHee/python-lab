# 각 줄이 성공하면 결과를, 실패하면 어떤 에러인지 예측할 것.

# (A)
a, b, c = [1, 2, 3]
print("  A:", a, b, c, " 예측:__")

# (B) — 실패?
try:
    a, b = [1, 2, 3]
    print("  B:", a, b)
except ValueError:
    print("  B: ValueError  예측:__")

# (C)
first, *rest = [1, 2, 3, 4]
print("  C:", first, rest, " 예측:__")

# (D)
*init, last = "abc"
print("  D:", init, last, " 예측:__")

# (E)
a, (b, c), d = 1, [2, 3], 4
print("  E:", a, b, c, d, " 예측:__")

# (F) — 무엇이 rest에?
a, *rest, z = [1]
try:
    print("  F:", a, rest, z, " 예측:__")
except Exception as e:
    print("  F: 에러", type(e).__name__)


