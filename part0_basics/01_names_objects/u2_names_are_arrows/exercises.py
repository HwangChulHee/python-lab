# 유제 1. 출력 예측 — 재대입 vs 변경
# ═══════════════════════════════════════════════════
# 각 블록의 출력을 실행 전에 예측하고, 화살표 그림으로 설명할 것.

# (A)
a = [1, 2, 3]
b = a
b = b + [4]           # ← 이건 재대입일까 변경일까?
# 예측: a =        b =
print("A) a =", a, "| b =", b)
# 왜? (b + [4]가 무엇을 만드는지):
#   →

# (B)
a = [1, 2, 3]
b = a
b += [4]              # ← += 는?  (A의 b = b + [4]와 같을까 다를까)
# 예측: a =        b =
print("B) a =", a, "| b =", b)
# A와 B의 결과가 다르다면 왜? (힌트: += 는 리스트에서 extend를 부른다):
#   →

# (C)
x = [1, 2]
y = x
x = [3, 4]
# 예측: y =
print("C) y =", y)
# x를 재대입했는데 y가 영향을 받나? 화살표로 설명:
#   →


# ═══════════════════════════════════════════════════
# 유제 2. 함수와 화살표
# ═══════════════════════════════════════════════════
def modify(lst):
    lst.append(99)        # 변경
    lst = [0, 0]          # 재대입
    lst.append(1)

original = [1, 2, 3]
modify(original)
# 예측: original =
print("\n유제2) original =", original)
# modify 안에서 append도 하고 재대입도 했는데 왜 이 결과인지,
# "화살표"로 두 줄을 각각 설명:
#   append(99) →
#   lst = [0,0] →


# ═══════════════════════════════════════════════════
# 유제 3. is 와 화살표
# ═══════════════════════════════════════════════════
import sys

a = [1, 2, 3]
b = a
c = [1, 2, 3]

# (a) 예측:
#   a is b →        a is c →        a == c →
print("\n유제3)")
print("  a is b:", a is b)
print("  a is c:", a is c)
print("  a == c:", a == c)
#
# (b) a is c는 False인데 a == c는 True인 이유를 화살표로 설명:
#   →
#
# (c) 이 시점에서 [1,2,3] 객체는 메모리에 몇 개 있나? 그리고
#     각각의 refcount는? (예측 후 sys.getrefcount로 확인)
#   예측 →
print("  refcount(a):", sys.getrefcount(a))
print("  refcount(c):", sys.getrefcount(c))