import sys

# ═══════════════════════════════════════════════════
# 유제 1. 크기 예측
# ═══════════════════════════════════════════════════
# (a) 실행 전 예측 — 왜 그렇게 생각하는지도 함께:
#     sys.getsizeof(0)      예측 → 28. 헤더가 16바이트인건 알고 있고 int형 데이터가 12바이트로 들어가는건 알고있어서
#     sys.getsizeof(1)      예측 → 28. 위와 동일
#     sys.getsizeof(2**64)  예측 → 28보다 큰 숫자. 숫자가 큰 경우에는 사이즈가 늘어난다는것을 알고있어서  (힌트: 파이썬 정수는 크기 제한이 없다)
#     sys.getsizeof([])     예측 → 56. examples에서 해봄
#     sys.getsizeof([1,2,3]) 예측 → 56. 이미 크기가 할당되어서 해당 범위를 넘어가면 그때커지지 않을까 (힌트: 안에 든 정수 크기가 포함될까?)
#
print("=== 유제1 ===")
for expr in ["0", "1", "2**64", "[]", "[1,2,3]", "[0]*100"]:
    print(f"  sys.getsizeof({expr:<8}) = {sys.getsizeof(eval(expr))}")
#
# (b) 틀린 것과 이유:
#   → [1,2,3] 틀렸네... 왜그럴까. 원소 3개인데 56 + 12 *3의 값이 아니라 88의 값이 나왔네.. 왜그럴까
#
# (c) [1,2,3]의 크기에 정수 세 개의 크기가 포함되지 않는 이유를 한 문장으로:
#   → 이미 크기가 할당되어서 해당 범위를 넘어가면 그때커지지 않을까


# ═══════════════════════════════════════════════════
# 유제 2. refcount 추적
# ═══════════════════════════════════════════════════
# 아래 각 줄 실행 후 obj의 refcount를 예측하고 확인할 것.
# (getrefcount는 항상 +1 된 값을 반환한다는 점 주의)
print("\n=== 유제2 ===")

obj = object()
print("  1) obj = object()        예측: 2  실제:", sys.getrefcount(obj))

lst = [obj]
print("  2) lst = [obj]           예측: 3  실제:", sys.getrefcount(obj))

d = {"key": obj, "key2": obj}
print("  3) d에 2번 담음           예측: 5  실제:", sys.getrefcount(obj))

def hold(x):
    return sys.getrefcount(x)
print("  4) 함수 인자로 넘긴 순간   예측: 6  실제:", hold(obj))

del lst
print("  5) del lst               예측: 5  실제:", sys.getrefcount(obj))

# 4번이 다른 것들과 왜 다른지 설명 (힌트: u4의 프레임):
#   → 매개변수로서 객체를 참조하기 때문에 refcount가 오른건데 뭐 특별한게 있나? 5번이 왜 4로 나온지는 모르겠음


