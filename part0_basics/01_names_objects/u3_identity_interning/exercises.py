# 아래 클래스는 __eq__를 오버라이드했다.
# is None 과 == None 의 차이가 드러난다.

class Weird:
    def __eq__(self, other):
        return True              # 무엇과 비교해도 같다고 함

w = Weird()
print("\n=== 유제3 ===")
print("  w == None :", w == None)     # 예측:__True
print("  w is None :", w is None)     # 예측:__False

